import type { Metadata } from "next";
import { loadLenderConfig } from "../../src/lib/config";
import { loadHealth } from "../../src/web/data";
import { Bars, type BarRow } from "../components/Bars";
import { Kpi, pct } from "../components/ui";

export const metadata: Metadata = { title: "Account health" };

export default function HealthPage() {
  const r = loadHealth("harborline");
  const cfg = loadLenderConfig("harborline");
  if (!r) return <main className="container"><p>Run <code>npm run health</code> to generate the synthetic dataset.</p></main>;
  const k = r.kpis;
  const worstDrop = Math.max(...r.dropoff.map((d) => d.rate));
  const worstOpt = Math.max(...r.sources.map((s) => s.opt_out_rate));
  const tc = r.transfer_connect;

  const funnel: BarRow[] = r.funnel.map((f) => ({
    label: f.label.replace("Answered: ", ""),
    value: f.share_of_replied,
    display: `${f.count} · ${pct(f.share_of_replied)}`,
    tip: `${f.label}: ${f.count} borrowers (${pct(f.share_of_replied)} of those who replied)`,
    emphasis: f.id === "credit_band" || f.id === "connected",
  }));
  const drop: BarRow[] = r.dropoff.map((d) => ({ label: d.label, value: d.rate, display: pct(d.rate), tip: `${d.label}: ${d.stopped} of ${d.asked} asked stopped replying`, emphasis: d.rate === worstDrop }));
  const connect: BarRow[] = [
    { label: "Weekdays", value: tc.weekday.rate, display: pct(tc.weekday.rate), tip: `Weekdays: ${tc.weekday.connected} of ${tc.weekday.transfers} transfers connected` },
    { label: "Weekends", value: tc.weekend.rate, display: pct(tc.weekend.rate), tip: `Weekends: ${tc.weekend.connected} of ${tc.weekend.transfers} transfers connected`, emphasis: true },
  ];
  const opt: BarRow[] = r.sources.map((s) => ({ label: s.label, value: s.opt_out_rate, display: pct(s.opt_out_rate), tip: `${s.label}: ${pct(s.opt_out_rate)} opted out (${s.leads} leads)`, emphasis: s.opt_out_rate === worstOpt }));
  const hgi: BarRow[] = r.sources.map((s) => ({ label: s.label, value: s.how_got_info_rate, display: pct(s.how_got_info_rate), tip: `${s.label}: ${pct(s.how_got_info_rate)} asked "how did you get my info?"`, emphasis: s.opt_out_rate === worstOpt }));
  const obj: BarRow[] = r.objections.map((o) => ({ label: o.label, value: o.share_of_replied, display: pct(o.share_of_replied), tip: `${o.label}: qualified ${pct(o.qualification_rate_with)} when raised vs ${pct(o.qualification_rate_without)} when not` }));

  return (
    <main className="container">
      <span className="badge badge-warn">SYNTHETIC DATA · NOT REAL RESULTS</span>
      <h1 style={{ marginTop: 12 }}>{cfg.lender.name} · Account health</h1>
      <p className="lead">
        {k.leads} simulated lead conversations, {r.period.start} to {r.period.end}. Generated by a seeded script with planted patterns, to
        show how I&apos;d run a weekly account review: read the numbers, then decide what to change in the agent.
      </p>

      <div className="kpis" style={{ marginTop: 20 }}>
        <Kpi label="Leads" value={String(k.leads)} sub={`${r.period.weeks} weeks`} />
        <Kpi label="Replied" value={pct(k.reply_rate)} sub={`${k.replied} of ${k.leads}`} />
        <Kpi label="Qualified" value={pct(k.qualification_rate)} sub={`${k.qualified} of ${k.replied} who replied`} />
        <Kpi label="Transferred" value={pct(k.transfer_rate)} sub={`${k.transferred} of ${k.qualified} qualified`} />
        <Kpi label="Loan officer connected" value={pct(k.transfer_connect_rate)} sub="of live transfers" />
        <Kpi label="Opted out" value={pct(k.opt_out_rate)} sub="of those who replied" />
        <Kpi label="Speed to lead" value={`${k.median_speed_to_lead_seconds}s`} sub="median first text" />
      </div>

      <h2>{r.recommendations.length} recommended agent changes</h2>
      <div className="stack">
        {r.recommendations.map((rec, i) => (
          <article key={rec.id} className="card rec">
            <div className="rec-num">{i + 1}</div>
            <div className="rec-body">
              <h3>{rec.title}</h3>
              <p className="rec-headline">{rec.headline}</p>
              <ul>{rec.evidence.map((e) => <li key={e}>{e}</li>)}</ul>
              <p><strong>Change:</strong> {rec.change}</p>
              <details><summary>Config change</summary><pre><code>{rec.config_snippet}</code></pre></details>
              <p style={{ marginTop: 8 }}><strong>How I&apos;d validate:</strong> {rec.validate}</p>
              <p className="small muted" style={{ margin: 0 }}>{rec.impact}</p>
            </div>
          </article>
        ))}
      </div>

      <h2>The evidence</h2>
      <div className="grid grid-2">
        <section className="card">
          <h3>Qualification funnel</h3>
          <p className="small muted">Share of borrowers who replied, by how far they got</p>
          <Bars rows={funnel} max={1} caption="Qualification funnel" />
          <details className="small"><summary>Show data table</summary>
            <table><tbody>{r.funnel.map((f) => <tr key={f.id}><th scope="row">{f.label}</th><td className="num">{f.count}</td><td className="num">{pct(f.share_of_replied)}</td></tr>)}</tbody></table>
          </details>
        </section>
        <section className="card">
          <h3>Drop-off by question</h3>
          <p className="small muted">Of borrowers asked each question, the share who stopped replying</p>
          <Bars rows={drop} caption="Drop-off by question" />
          <details className="small"><summary>Show data table</summary>
            <table><tbody>{r.dropoff.map((d) => <tr key={d.stage}><th scope="row">{d.label}</th><td className="num">{d.stopped} / {d.asked}</td><td className="num">{pct(d.rate)}</td></tr>)}</tbody></table>
          </details>
        </section>
        <section className="card">
          <h3>Live transfers that reached a loan officer</h3>
          <p className="small muted">Within the promised 5 minutes</p>
          <Bars rows={connect} max={1} caption="Transfer connect rate" />
        </section>
        <section className="card">
          <h3>Objections raised</h3>
          <p className="small muted">Share of conversations; hover for qualification impact</p>
          <Bars rows={obj} caption="Objection frequency" />
          <details className="small"><summary>Show data table</summary>
            <table><thead><tr><th>Objection</th><th className="num">Share</th><th className="num">Qualified if raised</th><th className="num">If not</th></tr></thead>
              <tbody>{r.objections.map((o) => <tr key={o.id}><th scope="row">{o.label}</th><td className="num">{pct(o.share_of_replied)}</td><td className="num">{pct(o.qualification_rate_with)}</td><td className="num">{pct(o.qualification_rate_without)}</td></tr>)}</tbody></table>
          </details>
        </section>
        <section className="card">
          <h3>Opt-out rate by lead source</h3>
          <p className="small muted">Of borrowers who replied</p>
          <Bars rows={opt} caption="Opt-out rate by lead source" />
        </section>
        <section className="card">
          <h3>&quot;How did you get my info?&quot; by lead source</h3>
          <p className="small muted">Of borrowers who replied</p>
          <Bars rows={hgi} caption="How-did-you-get-my-info rate by lead source" />
          <details className="small"><summary>Show data table</summary>
            <table><thead><tr><th>Source</th><th className="num">Leads</th><th className="num">Opted out</th><th className="num">Asked</th><th className="num">Qualified</th></tr></thead>
              <tbody>{r.sources.map((s) => <tr key={s.source}><th scope="row">{s.label}</th><td className="num">{s.leads}</td><td className="num">{pct(s.opt_out_rate)}</td><td className="num">{pct(s.how_got_info_rate)}</td><td className="num">{pct(s.qualification_rate)}</td></tr>)}</tbody></table>
          </details>
        </section>
      </div>
      <p className="small muted" style={{ marginTop: 16 }}>
        Download the synthetic dataset: <a href="/data/harborline-synthetic-calls.csv">CSV</a>. Every record is flagged synthetic.
      </p>
    </main>
  );
}
